def rows(ch):
    return [r.ljust(5, ".") for r in G.get(ch, G[" "])]


# Seven-pixel instrument numerals. The first bit stays clear for PrintBig's
# one-pixel alignment shift. Letters get a forward rake inside the same cell.
DASH_DIGITS = (
    "3e 63 67 6b 73 63 3e", "0c 1c 3c 0c 0c 0c 3f",
    "3e 63 03 0e 38 60 7f", "7e 03 06 1e 03 63 3e",
    "0e 1e 36 66 7f 06 06", "7f 60 7e 03 03 63 3e",
    "1e 30 60 7e 63 63 3e", "7f 03 06 0c 18 18 18",
    "3e 63 63 3e 63 63 3e", "3e 63 63 3f 03 06 3c",
)


def glyph_bytes(ch):
    if ch.isdigit():
        return list(bytes.fromhex(DASH_DIGITS[int(ch)])) + [0]
    data = []
    for y, pixels in enumerate(rows(ch)):
        value = sum(0x40 >> x for x, p in enumerate(pixels) if p == "#")
        data.append(value >> 1 if y < 3 else value)
    return data + [0]


def main(out):
    lines = ["; Generated by tools/make_font.py - do not edit", "Font:      ; ASCII 32-90, 8 bytes each"]
    for code in range(32, 91):
        data = glyph_bytes(chr(code))
        lines.append("        db " + ", ".join(f"${v:02X}" for v in data) + f"   ; {chr(code)!r}")
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/font_data.asm")
