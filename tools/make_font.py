def rows(ch):
    return [r.ljust(5, ".") for r in G.get(ch, G[" "])]


def main(out):
    lines = ["; Generated by tools/make_font.py - do not edit", "Font:      ; ASCII 32-90, 8 bytes each"]
    for code in range(32, 91):
        g = rows(chr(code))
        data = [sum(0x40 >> x for x in range(5) if r[x] == "#") for r in g] + [0]
        lines.append("        db " + ", ".join(f"${v:02X}" for v in data) + f"   ; {chr(code)!r}")
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/font_data.asm")
