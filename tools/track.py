#!/usr/bin/env python3
"""Compile a YAML track description into sjasmplus data.

Each segment becomes 4 bytes: length (word), curve (signed byte), reserved.
A zero-length entry ends the track; the track loops. The engine keeps the
position as a 16-bit value, so the segments must add up to exactly 65536:
the final segment is a straight that pads the lap.
usage: track.py track.yaml out.asm
"""
import sys
import yaml

LAP = 65536
SIGN_CURVE = 10          # bends at least this sharp get warning signs
SIGN_X = 240             # signs stand on the grass, clear of the kerb


def main(src, dst):
    track = yaml.safe_load(open(src))
    segs = [(int(s["length"]), int(s.get("curve", 0))) for s in track["segments"]]
    total = sum(length for length, _ in segs)
    if total > LAP:
        sys.exit(f"{src}: track is {total} units long, the maximum is {LAP}")
    if total < LAP:
        segs.append((LAP - total, 0))
    out = [f"; Generated by tools/track.py from {src} - do not edit",
           f"; {track.get('name', 'track')}: {len(segs)} segments", "Track:"]
    for length, curve in segs:
        if not 0 < length < 65536:
            sys.exit(f"{src}: bad segment length {length}")
        if not -128 <= curve <= 127:
            sys.exit(f"{src}: curve {curve} out of range")
        out.append(f"        dw {length}")
        out.append(f"        db {curve & 0xFF}, 0")
    out += ["TrackEnd:", "        dw 0", ""]

    # Scenery: expand the rules into one z-sorted list of 4-byte objects:
    # dw z ; db x / 4 (signed) ; db type. A type of $FF ends the list.
    types = {"palm": 0, "traffic": 1, "sign_r": 2, "sign_l": 3}   # see tools/make_scenery.py
    objs = []
    # curve warning signs: three on the outside of every sharp bend, before it
    z = 0
    for length, curve in segs:
        if abs(curve) >= SIGN_CURVE:
            kind = "sign_r" if curve > 0 else "sign_l"
            x = -SIGN_X if curve > 0 else SIGN_X
            for back in (1500, 1000, 500):
                if z - back >= 0:
                    objs.append((z - back, x // 4, types[kind]))
        z += length
    for rule in track.get("scenery", []):
        z = int(rule.get("from", 0))
        while z <= int(rule.get("to", LAP - 1)) and z < LAP:
            x = int(rule["x"]) // 4
            if not -128 <= x <= 127:
                sys.exit(f"{src}: scenery x {rule['x']} out of range")
            objs.append((z, x, types[rule["type"]]))
            z += int(rule["every"])
    objs.sort()
    out.append(f"; {len(objs)} scenery objects")
    out.append("Objects:")
    for z, x, t in objs:
        out.append(f"        dw {z}")
        out.append(f"        db {x & 0xFF}, {t}")
    out += ["ObjectsEnd:", "        dw 0", "        db 0, $FF", ""]
    open(dst, "w").write("\n".join(out))


if __name__ == "__main__":
    main(*sys.argv[1:3])
