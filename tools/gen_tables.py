#!/usr/bin/env python3
"""Generate precomputed lookup tables for the ZX Racer engine.

Writes an sjasmplus include file. Every table is 256-byte aligned so the
engine can index it with a single 8-bit register (H = page, L = index).
Tables of 96 road lines share a page in pairs (offset 0 and offset $80).
"""
import sys

ROAD_LINES = 96          # screen lines below the horizon
ROAD_Y0 = 96             # first road screen line
HALF_W_BOTTOM = 150      # road half-width (incl. rumble) on the bottom line, pixels
RUMBLE_FRAC = 0.15       # rumble strip width as a fraction of half-width
LANE_FRAC = 0.03         # centre-line half-width as a fraction of half-width
Z_NEAR = 128             # depth units at the bottom line (z = Z_NEAR*96/dy)



def screen_addr(y):
    return ((y & 0xC0) << 5) | ((y & 0x07) << 8) | ((y & 0x38) << 2)


def road_line(i):
    dy = i + 1
    w = round(HALF_W_BOTTOM * dy / ROAD_LINES)
    rw = max(1, round(w * RUMBLE_FRAC)) if w >= 2 else 0
    lw = round(w * LANE_FRAC)
    lw = min(lw, 7)
    z = round(Z_NEAR * ROAD_LINES / dy)
    return w, w - rw, lw, z


def page(name, *halves):
    """Emit a 256-byte aligned page holding up to two 128-entry tables."""
    out = ["        ALIGN 256", f"{name}:"]
    for off, (label, values) in zip((0, 0x80), halves):
        assert len(values) <= 128, label
        if off:
            out.append(f"        ORG {name} + $80")
        out.append(f"{label}:")
        for k in range(0, len(values), 16):
            out.append("        db " + ", ".join(f"${v & 0xFF:02X}" for v in values[k:k + 16]))
    out.append(f"        ORG {name} + 256")
    return out


def main(path):
    lines = ["; Generated by tools/gen_tables.py - do not edit", ""]

    # Screen line addresses (buffer A, $4000). Buffer B = high byte | $80.
    lines += ["        ALIGN 256", "ScrLo:"]
    lo = [screen_addr(y) & 0xFF for y in range(192)]
    hi = [0x40 | (screen_addr(y) >> 8) for y in range(192)]
    for k in range(0, 192, 16):
        lines.append("        db " + ", ".join(f"${v:02X}" for v in lo[k:k + 16]))
    lines += ["        ALIGN 256", "ScrHi:"]
    for k in range(0, 192, 16):
        lines.append("        db " + ", ".join(f"${v:02X}" for v in hi[k:k + 16]))
    road = [road_line(i) for i in range(ROAD_LINES)]
    lines += page("RoadPage", ("RoadW", [r[0] for r in road]),
                                  ("RoadX1", [r[1] for r in road]))
    lines += page("ZPage", ("ZLo", [r[3] & 0xFF for r in road]),
                               ("ZHi", [r[3] >> 8 for r in road]))
    lines += page("LanePage", ("LaneW", [r[2] for r in road]),
                                  ("Band", [0] * ROAD_LINES))
    lines += page("CXPage", ("CXLo", [0] * ROAD_LINES),
                                ("CXHi", [0] * ROAD_LINES))
    # Per-buffer state (three consecutive pages per buffer):
    #   St1: road centre cx low / high per line (kerb bytes drawn for that cx)
    #   St2: centre-line x per line ($FF = none)
    #   RowSt: kerb cell ranges a, b, c, d per row (4 bytes each) / band per row at +$80
    for buf in "AB":
        lines += page(f"State{buf}1", (f"St{buf}CxL", [0] * ROAD_LINES), (f"St{buf}CxH", [0] * ROAD_LINES))
        lines += page(f"State{buf}2", (f"St{buf}Lane", [0xFF] * ROAD_LINES))
        lines += page(f"State{buf}3", (f"Row{buf}Ranges", [0] * 48), (f"Row{buf}Band", [0xFF] * 12))

    # Mask page: LMask[b] = pixels left of bit b; lane masks for half-width w, start bit b
    lmask = [(~(0xFF >> b)) & 0xFF for b in range(8)]
    lane1, lane2 = [], []
    for w in range(8):
        for b in range(8):
            bits = 0
            for p in range(2 * w):
                bits |= 0x8000 >> (b + p)
            lane1.append(bits >> 8)
            lane2.append(bits & 0xFF)
    lines += ["        ALIGN 256", "MaskPage:", "LMask:"]
    lines.append("        db " + ", ".join(f"${v:02X}" for v in lmask))
    lines += ["        ORG MaskPage + $40", "LaneM1:"]
    for k in range(0, 64, 16):
        lines.append("        db " + ", ".join(f"${v:02X}" for v in lane1[k:k + 16]))
    lines += ["        ORG MaskPage + $80", "LaneM2:"]
    for k in range(0, 64, 16):
        lines.append("        db " + ", ".join(f"${v:02X}" for v in lane2[k:k + 16]))
    rmask = [0xFF >> b for b in range(8)]
    lmask_incl = [(~(0x7F >> b)) & 0xFF for b in range(8)]
    lines += ["        ORG MaskPage + $10", "RMask:",
              "        db " + ", ".join(f"${v:02X}" for v in rmask),
              "LMaskIncl:",
              "        db " + ", ".join(f"${v:02X}" for v in lmask_incl)]
    lines += ["        ORG MaskPage + 256"]

    # Kerb strips (written at run time): StripL = PAD zeros, left mask, PAD x $FF;
    # StripR = PAD x $FF, right mask, PAD zeros
    pad = 12
    lines += ["        ALIGN 256", "StripPage:", "StripL:",
              "        db " + ", ".join(["$00"] * pad + ["$00"] + ["$FF"] * pad),
              "        ORG StripPage + $20", "StripR:",
              "        db " + ", ".join(["$FF"] * pad + ["$00"] + ["$00"] * pad),
              "        ORG StripPage + 256"]

    lines.append("")

    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/tables.asm")
