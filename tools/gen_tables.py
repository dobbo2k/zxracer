#!/usr/bin/env python3
"""Generate precomputed lookup tables for the ZX Racer engine.

Writes an sjasmplus include file. Every table is 256-byte aligned so the
engine can index it with a single 8-bit register (H = page, L = index).
Tables of 96 road lines share a page in pairs (offset 0 and offset $80).
"""
import sys

ROAD_LINES = 96          # screen lines below the horizon
ROAD_Y0 = 96             # first road screen line
HALF_W_BOTTOM = 150      # road half-width (incl. rumble) on the bottom line, pixels
RUMBLE_FRAC = 0.15       # rumble strip width as a fraction of half-width
LANE_FRAC = 0.03         # centre-line half-width as a fraction of half-width
Z_NEAR = 128             # depth units at the bottom line (z = Z_NEAR*96/dy)

# Road fork at the end of a stage: from SPLIT_LEN before the end the road
# splits in two; each branch's centre moves out from the old centre line by
# fork_dx(d) world units (= bottom-line pixels), d = depth past the split.
SPLIT_LEN = 5000
FORK_K = 16                          # dx = d^2 / 65536 (the engine relies on it)


def fork_dx(d):
    return (d / 64) ** 2 / FORK_K if d > 0 else 0.0



def screen_addr(y):
    return ((y & 0xC0) << 5) | ((y & 0x07) << 8) | ((y & 0x38) << 2)


def road_line(i):
    dy = i + 1
    w = round(HALF_W_BOTTOM * dy / ROAD_LINES)
    rw = max(1, round(w * RUMBLE_FRAC)) if w >= 2 else 0
    lw = round(w * LANE_FRAC)
    lw = min(lw, 7)
    z = round(Z_NEAR * ROAD_LINES / dy)
    return w, w - rw, lw, z


def page(name, *halves):
    """Emit a 256-byte aligned page holding up to two 128-entry tables."""
    out = ["        ALIGN 256", f"{name}:"]
    for off, (label, values) in zip((0, 0x80), halves):
        assert len(values) <= 128, label
        if off:
            out.append(f"        ORG {name} + $80")
        out.append(f"{label}:")
        for k in range(0, len(values), 16):
            out.append("        db " + ", ".join(f"${v & 0xFF:02X}" for v in values[k:k + 16]))
        out.append(f"{label}_end:")             # (src/holes.asm uses what follows)
    out.append(f"        ORG {name} + 256")
    return out


def main(path):
    lines = ["; Generated by tools/gen_tables.py - do not edit", ""]

    # Screen line addresses (buffer A, $4000). Buffer B = high byte | $80.
    lines += ["        ALIGN 256", "ScrLo:"]
    lo = [screen_addr(y) & 0xFF for y in range(192)]
    hi = [0x40 | (screen_addr(y) >> 8) for y in range(192)]
    for k in range(0, 192, 16):
        lines.append("        db " + ", ".join(f"${v:02X}" for v in lo[k:k + 16]))
    lines += ["ScrLo_end:", "        ALIGN 256", "ScrHi:"]
    for k in range(0, 192, 16):
        lines.append("        db " + ", ".join(f"${v:02X}" for v in hi[k:k + 16]))
    lines += ["ScrHi_end:"]
    road = [road_line(i) for i in range(ROAD_LINES)]
    # Per-line road constants and pass-1 outputs, all indexed by road line i.
    lines += page("X1Page", ("RoadX1", [r[1] for r in road]),           # road half-width (no kerb)
                  ("RoadRW", [r[0] - r[1] for r in road]))              # kerb (rumble) width
    lines += page("LWPage", ("LaneWp", [r[2] if r[2] else 255 for r in road]),  # 255: no line
                  ("Band", [0] * ROAD_LINES))
    lines += page("ZPage", ("ZLo", [r[3] & 0xFF for r in road]),
                  ("LaneW", [r[2] for r in road]))
    lines += page("ZHiPage", ("ZHi", [r[3] >> 8 for r in road]))
    lines += page("DEPage", ("RoadD", [0xFF] * ROAD_LINES),             # first road pixel
                  ("RoadE", [0] * ROAD_LINES))                          # last road pixel
    # Fork: a branch's offset on screen line i (k = i + 1) is
    #   dx(Z - FD) * k / 96 = 24 / k - FD / 256 + FD^2 * k / 6291456
    # (Z = 12288 / k, FD = depth of the split); ForkT1 = 24 / k in 8.8 on odd
    # lines (fraction at i, integer part at i - 1).
    t1 = [0] * ROAD_LINES
    for i in range(1, ROAD_LINES, 2):
        v = round(6144 / (i + 1))
        t1[i], t1[i - 1] = v & 0xFF, v >> 8
    lines += page("LXPage", ("LaneX", [0xFF] * ROAD_LINES), ("ForkT1", t1))  # centre line x
    # Fork lines: road centre (16-bit, odd lines) and the second branch's
    # edges; per-row "both branches on screen" flags and DrawForkRow scratch
    lines += page("CXPage", ("CXLo", [0] * ROAD_LINES), ("CXHi", [0] * ROAD_LINES))
    lines += page("DE2Page", ("RoadD2", [0xFF] * ROAD_LINES), ("RoadE2", [0] * ROAD_LINES))
    lines += ["RowFork EQU DE2Page + $60", "ForkCls EQU DE2Page + $E0"]
    # DxTab[d >> 6] = fork_dx / 4 (capped)
    lines += [f"SPLIT_LEN EQU {SPLIT_LEN}", "        ALIGN 256", "DxTab:"]
    dx = [min(255, round(fork_dx(k * 64 + 32) / 4)) for k in range(256)]
    for k in range(0, 256, 16):
        lines.append("        db " + ", ".join(f"${v:02X}" for v in dx[k:k + 16]))
    # Scenery: perspective scale (i+1)/96 in 1/256 and pre-scaled size per line
    sizes = [64, 48, 36, 27, 20, 15, 11, 8, 6]         # must match tools/make_scenery.py
    scale = [min(255, round((i + 1) * 256 / ROAD_LINES)) for i in range(ROAD_LINES)]
    size_for = []
    for i in range(ROAD_LINES):
        want = 64 * (i + 1) / ROAD_LINES
        k = min(range(len(sizes)), key=lambda k: abs(sizes[k] - want))
        size_for.append(max(k, 1) if want >= 4 else 0xFF)     # largest size not used: too costly
    lines += page("ObjPage", ("ObjScale", scale), ("SizeForLine", size_for))
    # Depth -> screen line for scenery: largest i with Z[i] >= z.
    # ZNear[z >> 2] for z < 1024, ZFar[z >> 4] for z < 4096 ($FF: none).
    zs = [road_line(i)[3] for i in range(ROAD_LINES)]
    def zline(z):
        best = 0xFF
        for i in range(ROAD_LINES):
            if zs[i] >= z:
                best = i
        return best
    lines += ["        ALIGN 256", "ZNear:"]
    vals = [zline(max(1, k * 4)) for k in range(256)]
    for k in range(0, 256, 16):
        lines.append("        db " + ", ".join(f"${v:02X}" for v in vals[k:k + 16]))
    lines += ["ZFar:"]
    vals = [zline(max(1, k * 16)) for k in range(256)]
    for k in range(0, 256, 16):
        lines.append("        db " + ", ".join(f"${v:02X}" for v in vals[k:k + 16]))

    # Per-buffer state (three consecutive pages per buffer):
    #   St1: first / last road pixel per line (kerb bytes drawn for those)
    #   St2: centre-line x per line ($FF = none)
    #   RowSt: kerb cell ranges a, b, c, d per row (4 bytes each) / band per row at +$80
    for buf in "AB":
        lines += page(f"State{buf}1", (f"St{buf}D", [0] * ROAD_LINES), (f"St{buf}E", [0] * ROAD_LINES))
        lines += page(f"State{buf}2", (f"St{buf}Lane", [0xFF] * ROAD_LINES))
        lines += page(f"State{buf}3", (f"Row{buf}Ranges", [0] * 48), (f"Row{buf}Band", [0xFF] * 12))

    # Mask page: LMask[b] = pixels left of bit b; lane masks for half-width w, start bit b
    lmask = [(~(0xFF >> b)) & 0xFF for b in range(8)]
    lane1, lane2 = [], []
    for w in range(8):
        for b in range(8):
            bits = 0
            for p in range(2 * w):
                bits |= 0x8000 >> (b + p)
            lane1.append(bits >> 8)
            lane2.append(bits & 0xFF)
    lines += ["        ALIGN 256", "MaskPage:", "LMask:"]
    lines.append("        db " + ", ".join(f"${v:02X}" for v in lmask))
    lines += ["LMask_end:", "        ORG MaskPage + $40", "LaneM1:"]
    for k in range(0, 64, 16):
        lines.append("        db " + ", ".join(f"${v:02X}" for v in lane1[k:k + 16]))
    lines += ["LaneM1_end:", "        ORG MaskPage + $80", "LaneM2:"]
    for k in range(0, 64, 16):
        lines.append("        db " + ", ".join(f"${v:02X}" for v in lane2[k:k + 16]))
    lines += ["LaneM2_end:"]
    rmask = [0xFF >> b for b in range(8)]
    lmask_incl = [(~(0x7F >> b)) & 0xFF for b in range(8)]
    lines += ["        ORG MaskPage + $10", "RMask:",
              "        db " + ", ".join(f"${v:02X}" for v in rmask),
              "LMaskIncl:",
              "        db " + ", ".join(f"${v:02X}" for v in lmask_incl), "LMaskIncl_end:"]
    lines += ["        ORG MaskPage + 256"]

    # Kerb strips (written at run time): StripL = PAD zeros, left mask, PAD x $FF;
    # StripR = PAD x $FF, right mask, PAD zeros
    pad = 12
    lines += ["        ALIGN 256", "StripPage:", "StripL:",
              "        db " + ", ".join(["$00"] * pad + ["$00"] + ["$FF"] * pad), "StripL_end:",
              "        ORG StripPage + $20", "StripR:",
              "        db " + ", ".join(["$FF"] * pad + ["$00"] + ["$00"] * pad), "StripR_end:",
              "        ORG StripPage + 256"]

    lines.append("")

    with open(path, "w") as f:
        f.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/tables.asm")
