#!/usr/bin/env python3
"""Draw the horizon panorama and build its pre-shifted data.

A 256 x 16 pixel band of distant mountains that tiles horizontally, saved as
assets/gfx/horizon.png. Output: 4 copies, each rotated left by 0/2/4/6
pixels, 16 lines of 32 bytes each (copy-major).
usage: make_horizon.py out.asm
"""
import math
import random
import sys
from PIL import Image

W, H = 256, 16


def ridge(seed, top, bottom, octaves):
    """Periodic ridge line, normalised to lie between rows top and bottom."""
    rnd = random.Random(seed)
    phases = [(rnd.random() * 2 * math.pi, k) for k in octaves]
    raw = []
    for x in range(W):
        y = 0
        for ph, k in phases:
            y += math.sin(2 * math.pi * k * x / W + ph) / k ** 0.8
        raw.append(y)
    lo, hi = min(raw), max(raw)
    return [top + (v - lo) / (hi - lo) * (bottom - top) for v in raw]


def panorama():
    im = Image.new("1", (W, H), 0)
    far = ridge(7, 1, 13, [1, 2, 3, 5, 8, 13])          # distant range with peaks
    near = ridge(21, 9, 14, [2, 4, 7, 11, 17])          # low foothills
    for x in range(W):
        top = min(far[x], near[x])
        for y in range(max(0, int(top)), H):
            im.putpixel((x, y), 1)
        # snow caps: leave the very tops of the high peaks as gaps (sky shows)
        if far[x] < 4:
            for y in range(int(far[x]) + 1, int(far[x]) + 3):
                if (x + y) % 2 == 0 and 0 <= y < H:
                    im.putpixel((x, y), 0)
    return im


def main(out):
    im = panorama()
    im.convert("L").point(lambda v: 255 - v).save("assets/gfx/horizon.png")
    lines = ["; Generated by tools/make_horizon.py - do not edit",
             f"PANO_H EQU {H}", "Panorama:"]
    for s in range(4):
        for y in range(H):
            row = []
            for b in range(32):
                v = 0
                for x in range(8):
                    if im.getpixel(((b * 8 + x + 2 * s) % W, y)):
                        v |= 0x80 >> x
                row.append(v)
            lines.append("        db " + ", ".join(f"${v:02X}" for v in row))
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "build/horizon_data.asm")
